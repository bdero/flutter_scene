/// A 5-bit channel expanded to 8 bits, as ETC1 and BC1 decoders do.
int expand5(int v) => (v << 3) | (v >> 2);

/// A 6-bit channel expanded to 8 bits, as BC1 decoders do.
int expand6(int v) => (v << 2) | (v >> 4);

int _clamp255(int v) => v < 0 ? 0 : (v > 255 ? 255 : v);

/// The four colors (one channel) an ETC1S endpoint decodes to, by selector:
/// the expanded 5-bit [value] plus each modifier of intensity table [inten],
/// clamped.
List<int> etc1sChannelColors(int value, int inten) {
  final base = expand5(value);
  return [for (final m in etc1IntenTables[inten]) _clamp255(base + m)];
}

// BC1 --------------------------------------------------------------------

/// The used-selector ranges (lowest, highest) the BC1 table solves.
const List<(int, int)> etc1sBc1Ranges = [
  (0, 3),
  (1, 3),
  (0, 2),
  (1, 2),
  (2, 3),
  (0, 1),
];

/// Candidate maps from the four ETC1S selectors to BC1 palette positions
/// (0 low endpoint, 3 high endpoint, 1 and 2 the thirds between).
const List<List<int>> etc1sBc1Mappings = [
  [0, 0, 1, 1],
  [0, 0, 1, 2],
  [0, 0, 1, 3],
  [0, 0, 2, 3],
  [0, 1, 1, 1],
  [0, 1, 2, 2],
  [0, 1, 2, 3],
  [0, 2, 3, 3],
  [1, 2, 2, 2],
  [1, 2, 3, 3],
];

/// Entries per (intensity, channel value) row of a BC1 table: one solution
/// per selector range and mapping.
const int etc1sBc1RowLength = 6 * 10;

/// The ETC1S-to-BC1 table for a [bits]-bit channel (5 for red and blue, 6
/// for green): per intensity, channel value, selector range and mapping, the
/// (low, high) endpoint pair with the least squared error. This exhaustive
/// search reproduces basis_universal's tables exactly;
/// `tool/generate_etc1s_tables.dart` stores its result.
Uint8List buildEtc1sBc1Table(int bits) {
  final levels = 1 << bits;
  // Every endpoint pair's four palette values, pair index hi * levels + lo.
  final palette = Int32List(levels * levels * 4);
  for (var hi = 0; hi < levels; hi++) {
    for (var lo = 0; lo < levels; lo++) {
      final c0 = bits == 5 ? expand5(lo) : expand6(lo);
      final c3 = bits == 5 ? expand5(hi) : expand6(hi);
      final o = (hi * levels + lo) * 4;
      palette[o] = c0;
      palette[o + 1] = (c0 * 2 + c3) ~/ 3;
      palette[o + 2] = (c3 * 2 + c0) ~/ 3;
      palette[o + 3] = c3;
    }
  }
  final table = Uint8List(8 * 32 * etc1sBc1RowLength * 2);
  var k = 0;
  for (var inten = 0; inten < 8; inten++) {
    for (var value = 0; value < 32; value++) {
      final colors = etc1sChannelColors(value, inten);
      for (final (low, high) in etc1sBc1Ranges) {
        for (final mapping in etc1sBc1Mappings) {
          var bestError = 0x7FFFFFFF;
          var bestPair = 0;
          for (var pair = 0; pair < levels * levels; pair++) {
            var error = 0;
            for (var s = low; s <= high; s++) {
              final d = colors[s] - palette[pair * 4 + mapping[s]];
              error += d * d;
            }
            if (error < bestError) {
              bestError = error;
              bestPair = pair;
            }
          }
          table[k++] = bestPair % levels;
          table[k++] = bestPair ~/ levels;
        }
      }
    }
  }
  return table;
}

/// One channel's decoded BC1 table, with each solution's squared error.
class Etc1sBc1Table {
  Etc1sBc1Table._(this.bits, Uint8List pairs)
    : lo = Uint8List(pairs.length ~/ 2),
      hi = Uint8List(pairs.length ~/ 2),
      error = Uint32List(pairs.length ~/ 2) {
    final expand = bits == 5 ? expand5 : expand6;
    for (var i = 0; i < lo.length; i++) {
      lo[i] = pairs[i * 2];
      hi[i] = pairs[i * 2 + 1];
    }
    for (var row = 0; row < 8 * 32; row++) {
      final colors = etc1sChannelColors(row % 32, row ~/ 32);
      for (var r = 0; r < etc1sBc1Ranges.length; r++) {
        final (low, high) = etc1sBc1Ranges[r];
        for (var m = 0; m < etc1sBc1Mappings.length; m++) {
          final i = row * etc1sBc1RowLength + r * etc1sBc1Mappings.length + m;
          final c0 = expand(lo[i]);
          final c3 = expand(hi[i]);
          final palette = [c0, (c0 * 2 + c3) ~/ 3, (c3 * 2 + c0) ~/ 3, c3];
          var e = 0;
          for (var s = low; s <= high; s++) {
            final d = colors[s] - palette[etc1sBc1Mappings[m][s]];
            e += d * d;
          }
          error[i] = e;
        }
      }
    }
  }

  /// The 5-bit table (red and blue), decoded on first use.
  static final Etc1sBc1Table fiveBit = Etc1sBc1Table._(
    5,
    base64.decode(etc1sBc1Table5Data),
  );

  /// The 6-bit table (green), decoded on first use.
  static final Etc1sBc1Table sixBit = Etc1sBc1Table._(
    6,
    base64.decode(etc1sBc1Table6Data),
  );

  final int bits;
  final Uint8List lo;
  final Uint8List hi;
  final Uint32List error;

  /// Index of the first solution (mapping 0) for [inten], channel [value]
  /// and selector [range].
  static int indexOf(int inten, int value, int range) =>
      (inten * 32 + value) * etc1sBc1RowLength +
      range * etc1sBc1Mappings.length;
}

/// Index into [etc1sBc1Ranges] for each used-selector pair, `low * 4 + high`
/// (only low < high is meaningful).
final Uint8List etc1sBc1RangeIndex = () {
  final index = Uint8List(16);
  for (var i = 0; i < etc1sBc1Ranges.length; i++) {
    final (low, high) = etc1sBc1Ranges[i];
    index[low * 4 + high] = i;
  }
  return index;
}();

/// For each mapping, the 256-entry translation of a row of four ETC1S
/// selectors (2 bits each, x0 lowest) to BC1 indices, for a block whose low
/// endpoint is color0 ([bc1RowForward]) or color1 ([bc1RowInverted]).
final List<Uint8List> bc1RowForward = _bc1RowTables(inverted: false);
final List<Uint8List> bc1RowInverted = _bc1RowTables(inverted: true);

List<Uint8List> _bc1RowTables({required bool inverted}) {
  // Palette position to BC1 index: 0 -> color0, 3 -> color1, and the thirds
  // are indices 2 (nearer color0) and 3 (nearer color1).
  const positionToIndex = [0, 2, 3, 1];
  // Swapping color0 and color1 swaps indices 0/1 and 2/3.
  const swapped = [1, 0, 3, 2];
  return [
    for (final mapping in etc1sBc1Mappings)
      Uint8List.fromList([
        for (var row = 0; row < 256; row++)
          [0, 1, 2, 3].fold<int>(0, (bits, x) {
            var index = positionToIndex[mapping[(row >> (x * 2)) & 3]];
            if (inverted) index = swapped[index];
            return bits | (index << (x * 2));
          }),
      ]),
  ];
}

/// Best BC1 endpoint pair for a solid channel value, placing it at the 2/3
/// point (`selector1`) or on the high endpoint (`selector0`), with
/// basis_universal's error rule.
class Bc1SingleColor {
  Bc1SingleColor._(int bits, {required bool selector1})
    : lo = Uint8List(256),
      hi = Uint8List(256) {
    final levels = 1 << bits;
    final expand = bits == 5 ? expand5 : expand6;
    for (var value = 0; value < 256; value++) {
      var lowest = 256;
      for (var l = 0; l < (selector1 ? levels : 1); l++) {
        for (var h = 0; h < levels; h++) {
          final le = expand(l);
          final he = expand(h);
          final int e;
          if (selector1) {
            e =
                ((he * 2 + le) ~/ 3 - value).abs() +
                ((he - le).abs() * 3) ~/ 100;
          } else {
            e = (he - value).abs();
          }
          if (e < lowest) {
            lo[value] = l;
            hi[value] = h;
            lowest = e;
          }
        }
      }
    }
  }

  static final Bc1SingleColor match5Selector1 = Bc1SingleColor._(
    5,
    selector1: true,
  );
  static final Bc1SingleColor match6Selector1 = Bc1SingleColor._(
    6,
    selector1: true,
  );
  static final Bc1SingleColor match5Selector0 = Bc1SingleColor._(
    5,
    selector1: false,
  );
  static final Bc1SingleColor match6Selector0 = Bc1SingleColor._(
    6,
    selector1: false,
  );

  final Uint8List lo;
  final Uint8List hi;
}

