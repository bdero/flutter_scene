// Regenerates test/support/iwer_bundle.g.dart from third_party/iwer/iwer.min.js.
//
//     dart run tool/vendor_iwer.dart
//
// The bundle is stored base64-encoded so no character in the minified source
// needs escaping, and the browser tests decode it before injecting a script.
import 'dart:convert';
import 'dart:io';

void main() {
  final source = File('third_party/iwer/iwer.min.js').readAsBytesSync();
  final encoded = base64.encode(source);
  final buffer = StringBuffer()
    ..writeln('// GENERATED by tool/vendor_iwer.dart from')
    ..writeln(
      '// third_party/iwer/iwer.min.js (IWER 2.5.0, MIT, Meta Platforms,',
    )
    ..writeln(
      '// Inc. and affiliates). Do not edit; rerun the tool after an update.',
    )
    ..writeln()
    ..writeln('/// The IWER browser bundle, base64-encoded.')
    ..writeln('const String iwerBundleBase64 =');
  for (var i = 0; i < encoded.length; i += 76) {
    final end = i + 76 < encoded.length ? i + 76 : encoded.length;
    final last = end == encoded.length;
    buffer.writeln("    '${encoded.substring(i, end)}'${last ? ';' : ''}");
  }
  buffer
    ..writeln()
    ..writeln('/// The byte length of the bundle, for the freshness check.')
    ..writeln('const int iwerBundleLength = ${source.length};');
  File('test/support/iwer_bundle.g.dart').writeAsStringSync(buffer.toString());
  stdout.writeln(
    'wrote test/support/iwer_bundle.g.dart (${source.length} bytes)',
  );
}
